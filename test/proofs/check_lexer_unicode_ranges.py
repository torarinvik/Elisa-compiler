def split_top_level(expression: str, delimiter: str) -> list[str]:
    pieces = []
    start = 0
    depth = 0
    index = 0
    while index < len(expression):
        char = expression[index]
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth < 0:
                raise SystemExit("unbalanced generated Unicode predicate")
        if depth == 0 and expression.startswith(delimiter, index):
            pieces.append(expression[start:index].strip())
            index += len(delimiter)
            start = index
            continue
        index += 1
    if depth != 0:
        raise SystemExit("unbalanced generated Unicode predicate")
    pieces.append(expression[start:].strip())
    return pieces


def parse_table() -> dict:
    text = SOURCE.read_text()
    if not text.startswith("# Generated by test/parity/generate_lexer_unicode_ranges.go; Unicode "):
        raise SystemExit("Unicode predicate source is no longer identified as generator output")
    functions = {}
    for match in FUNCTION_RE.finditer(text):
        name, expression = match.groups()
        if name in functions:
            raise SystemExit(f"duplicate generated Unicode predicate {name}")
        functions[name] = expression
    if len(functions) != 71:
        raise SystemExit(f"expected 71 generated Unicode predicates, found {len(functions)}")

    table = {}
    for name, expression in functions.items():
        if name in {"is_unicode_letter_codepoint", "is_unicode_digit_codepoint"}:
            wrapper = CALL_RE.fullmatch(expression)
            if not wrapper or wrapper.group(1) not in functions:
                raise SystemExit(f"{name} no longer delegates to one generated classifier")
            table[name] = {"kind": "wrapper", "target": wrapper.group(1)}
            continue
        terms = split_top_level(expression, " or ")
        atoms = []
        for term in terms:
            match = ATOM_RE.fullmatch(term)
            if match:
                lower, upper, singleton = match.groups()
                if singleton is not None:
                    lower = upper = singleton
                atoms.append((lower, upper))
        if atoms and len(atoms) == len(terms):
            table[name] = {"kind": "leaf", "atoms": atoms}
            continue

        calls = [CALL_RE.fullmatch(term) for term in terms]
        if calls and all(calls) and "dispatch" not in name:
            children = [match.group(1) for match in calls]
            if any(child not in functions for child in children):
                raise SystemExit(f"{name} calls a missing generated predicate")
            table[name] = {"kind": "aggregate", "children": children}
            continue

        dispatch = [DISPATCH_RE.fullmatch(term) for term in terms]
        if dispatch and all(dispatch) and "dispatch" in name:
            routes = [(match.group(1), match.group(2), match.group(3)) for match in dispatch]
            if any(target not in functions for _, _, target in routes):
                raise SystemExit(f"{name} routes to a missing generated predicate")
            table[name] = {"kind": "dispatch", "routes": routes}
            continue

        raise SystemExit(f"unsupported generated Unicode predicate shape in {name}")

    kinds = Counter(item["kind"] for item in table.values())
    if kinds != Counter({"leaf": 61, "aggregate": 6, "dispatch": 2, "wrapper": 2}):
        raise SystemExit(f"unexpected generated Unicode predicate shape counts: {dict(kinds)}")
    if sum(len(item["atoms"]) for item in table.values() if item["kind"] == "leaf") != 709:
        raise SystemExit("generated Unicode interval atom count changed")
    return table


def ensure_interval(lower: str, upper: str) -> str:
    return (f"({lower} >= 0 and {lower} <= {upper} and {upper} <= {SCALAR_MAX} "
            f"and ({upper} < {SURROGATE_MIN} or {lower} > {SURROGATE_MAX}))")


def ensure_page_interval_conditions(lower: str, upper: str) -> tuple[str, ...]:
    return (f"{lower} >= 0", f"{lower} <= {upper}", f"{upper} <= {SCALAR_MAX}")


def render_bounds(table: dict) -> str:
    lines = ["# Scalar validity and strict ordering for every generated Unicode interval.", ""]
    for name, item in table.items():
        if item["kind"] != "leaf":
            continue
        lines.extend((f"def {name}_intervals_are_valid_and_ordered() -> bool:",))
        atoms = item["atoms"]
        for lower, upper in atoms:
            lines.append(f"    ensure {ensure_interval(lower, upper)}")
        for (_, previous_upper), (next_lower, _) in zip(atoms, atoms[1:]):
            lines.append(f"    ensure {previous_upper} < {next_lower}")
        lines.extend(("    ensure result == true", "    return true", ""))

    for name, item in table.items():
        if item["kind"] != "dispatch":
            continue
        lines.append(f"def {name}_page_intervals_are_valid_and_ordered() -> bool:")
        routes = item["routes"]
        for lower, upper, _ in routes:
            for condition in ensure_page_interval_conditions(lower, upper):
                lines.append(f"    ensure {condition}")
        for (_, previous_upper, _), (next_lower, _, _) in zip(routes, routes[1:]):
            lines.append(f"    ensure {previous_upper} < {next_lower}")
        lines.extend(("    ensure result == true", "    return true", ""))
    return "\n".join(lines).rstrip() + "\n"


def render_model(table: dict) -> str:
    lines = [
        "# The checker binds each atom flag to one exact source interval or singleton.",
        "# These lemmas prove OR reduction and page routing after abstraction.",
        "",
    ]
    for name, item in table.items():
        if item["kind"] == "leaf":
            params = []
            for index, (lower, upper) in enumerate(item["atoms"]):
                atom_label = lower[2:].lower()
                if lower != upper:
                    atom_label += "_" + upper[2:].lower()
                params.append(f"atom_{index:02d}_{atom_label}_reported: bool")
            expression = " or ".join(param.split(":", 1)[0] for param in params)
            theorem = f"proof_{name}_accumulates_source_intervals"
        elif item["kind"] == "aggregate":
            params = [f"{child}_reported: bool" for child in item["children"]]
            expression = " or ".join(param.split(":", 1)[0] for param in params)
            theorem = f"proof_{name}_accumulates_source_parts"
        elif item["kind"] == "dispatch":
            params = ["value: i64"]
            route_terms = []
            for index, (lower, upper, _) in enumerate(item["routes"]):
                params.append(f"page_{index:02d}_reported: bool")
                route_terms.append(
                    f"((value >= {lower} and value <= {upper}) and page_{index:02d}_reported)"
                )
            expression = " or ".join(route_terms)
            theorem = f"proof_{name}_routes_inside_page_intervals"
        else:
            params = [f"dispatch_reported: bool"]
            expression = "dispatch_reported"
            theorem = f"proof_{name}_preserves_dispatch_result"

        signature = ", ".join(params)
        lines.append(f"def {theorem}({signature}) -> bool:")
        lines.append(f"    ensure result == ({expression})")
        lines.append(f"    return {expression}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def hex_literal(value: int) -> str:
    return f"0x{value:X}"


def leaf_at_expression(table: dict, name: str, value: int) -> str:
    item = table[name]
    if item["kind"] != "leaf":
        raise SystemExit(f"{name} is not a source interval predicate")
    value_text = hex_literal(value)
    terms = []
    for lower, upper in item["atoms"]:
        if lower == upper:
            terms.append(f"{value_text} == {lower}")
        else:
            terms.append(f"({value_text} >= {lower} and {value_text} <= {upper})")
    return " or ".join(terms)


def dispatch_at_expression(table: dict, name: str, value: int, selected_page: Optional[int]) -> str:
    item = table[name]
    if item["kind"] != "dispatch":
        raise SystemExit(f"{name} is not a page dispatcher")
    value_text = hex_literal(value)
    terms = []
    for index, (lower, upper, _) in enumerate(item["routes"]):
        reported = "true" if selected_page is None or index == selected_page else "false"
        terms.append(
            f"(({value_text} >= {lower} and {value_text} <= {upper}) and {reported})"
        )
    return " or ".join(terms)


def render_witnesses(table: dict) -> str:
    cjk_lower, cjk_upper = table["unicode_letter_p00_r21"]["atoms"][3]
    digit_lower, digit_upper = table["unicode_digit_p01_r02"]["atoms"][4]
    first_letter_lower, _ = table["unicode_letter_p00_r00"]["atoms"][0]
    _, final_letter_upper = table["unicode_letter_p03_r00"]["atoms"][-1]
    page_boundary = int(table["unicode_letter_dispatch_00"]["routes"][1][0], 16)
    page_limit = int(table["unicode_letter_dispatch_00"]["routes"][-1][1], 16)
    cases = [
        ("unicode_letter_cjk_extension_a_lower_boundary_is_in_table", "true",
         leaf_at_expression(table, "unicode_letter_p00_r21", int(cjk_lower, 16))),
        ("unicode_letter_cjk_extension_a_upper_boundary_is_in_table", "true",
         leaf_at_expression(table, "unicode_letter_p00_r21", int(cjk_upper, 16))),
        ("unicode_digit_mathematical_digit_lower_boundary_is_in_table", "true",
         leaf_at_expression(table, "unicode_digit_p01_r02", int(digit_lower, 16))),
        ("unicode_digit_mathematical_digit_upper_boundary_is_in_table", "true",
         leaf_at_expression(table, "unicode_digit_p01_r02", int(digit_upper, 16))),
        ("unicode_digit_scalar_before_mathematical_digits_is_outside_table", "false",
         leaf_at_expression(table, "unicode_digit_p01_r02", int(digit_lower, 16) - 1)),
        ("unicode_digit_scalar_after_mathematical_digits_is_outside_table", "false",
         leaf_at_expression(table, "unicode_digit_p01_r02", int(digit_upper, 16) + 1)),
        ("unicode_letter_first_generated_lower_boundary_is_in_table", "true",
         leaf_at_expression(table, "unicode_letter_p00_r00", int(first_letter_lower, 16))),
        ("unicode_letter_final_generated_upper_boundary_is_in_table", "true",
         leaf_at_expression(table, "unicode_letter_p03_r00", int(final_letter_upper, 16))),
        ("unicode_letter_scalar_after_final_generated_range_is_outside_table", "false",
         leaf_at_expression(table, "unicode_letter_p03_r00", int(final_letter_upper, 16) + 1)),
        ("unicode_letter_supplementary_boundary_routes_to_page_one", "true",
         dispatch_at_expression(table, "unicode_letter_dispatch_00", page_boundary, 1)),
        ("unicode_letter_scalar_after_last_dispatch_page_is_unrouted", "false",
         dispatch_at_expression(table, "unicode_letter_dispatch_00", page_limit + 1, None)),
        ("unicode_surrogate_interval_is_not_a_scalar_interval", "false",
         ensure_interval("0xD800", "0xDFFF")),
    ]
    lines = ["# Concrete endpoint witnesses rendered from the generated classifier.", ""]
    for name, expected, expression in cases:
        lines.extend((f"def {name}() -> bool:", f"    ensure result == {expected}",
                      f"    return {expression}", ""))
    return "\n".join(lines).rstrip() + "\n"


def render_negative(table: dict) -> str:
    by_atoms = {}
    for name, item in table.items():
        if item["kind"] == "leaf":
            for index, interval in enumerate(item["atoms"]):
                by_atoms[(name, index)] = interval
    cjk_lower, cjk_upper = by_atoms[("unicode_letter_p00_r21", 3)]
    digit_lower, digit_upper = by_atoms[("unicode_digit_p01_r02", 4)]
    first_atoms = table["unicode_letter_p00_r00"]["atoms"]
    previous_upper = first_atoms[0][1]
    next_lower = first_atoms[1][0]
    letter_routes = table["unicode_letter_dispatch_00"]["routes"]
    wrong_page_value = letter_routes[1][0]
    outside_page_value = hex(int(letter_routes[-1][1], 16) + 1).upper().replace("0X", "0x")
    wrong_page_terms = []
    outside_page_terms = []
    for index, (lower, upper, _) in enumerate(letter_routes):
        wrong_page_terms.append(
            f"(({wrong_page_value} >= {lower} and {wrong_page_value} <= {upper}) and "
            f"{'true' if index == 0 else 'false'})"
        )
        outside_page_terms.append(
            f"(({outside_page_value} >= {lower} and {outside_page_value} <= {upper}) and true)"
        )

    lines = [
        "# False controls: each intentionally contradicts a concrete source-bound fact.",
        "",
        "def false_cjk_extension_a_start_is_not_a_letter() -> bool:",
        "    ensure result == true",
        f"    return not (0x3400 >= {cjk_lower} and 0x3400 <= {cjk_upper})",
        "",
        "def false_mathematical_decimal_digit_start_is_not_a_digit() -> bool:",
        "    ensure result == true",
        f"    return not (0x1D7CE >= {digit_lower} and 0x1D7CE <= {digit_upper})",
        "",
        "def false_supplementary_letter_uses_the_bmp_page() -> bool:",
        "    ensure result == true",
        "    return " + " or ".join(wrong_page_terms),
        "",
        "def false_codepoint_above_generated_pages_is_reported() -> bool:",
        "    ensure result == true",
        "    return " + " or ".join(outside_page_terms),
        "",
        "def false_surrogate_span_is_a_scalar_interval() -> bool:",
        "    ensure result == true",
        f"    return {ensure_interval('0xD800', '0xDFFF')}",
        "",
        "def false_generated_intervals_are_not_strictly_ordered() -> bool:",
        "    ensure result == true",
        f"    return {previous_upper} >= {next_lower}",
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def check_source_binding(table: dict) -> None:
    expected = {
        BOUNDS: render_bounds(table),
        POSITIVE: render_model(table),
        NEGATIVE: render_negative(table),
        WITNESSES: render_witnesses(table),
    }
    for path, text in expected.items():
        if not path.is_file() or path.read_text() != text:
            raise SystemExit(f"{path.name} is not the deterministic source projection of {SOURCE.relative_to(ROOT)}")

    generator_run = subprocess.run(
        ["go", "run", str(GENERATOR)], cwd=ROOT, capture_output=True,
        text=True, timeout=180, check=True,
    )
    if generator_run.stdout != SOURCE.read_text():
        raise SystemExit("generated Unicode classifier differs from the checked-in Go Unicode tables")

    facade_text = FACADE.read_text()
    if 'include "./lexer_unicode_ranges.elisa"' not in facade_text:
        raise SystemExit("lexer facade no longer includes the generated Unicode classifier")
    core_text = CORE.read_text()
    try:
        start = core_text.split("def unicode_identifier_start_width(", 1)[1].split(
            "def unicode_identifier_char_width(", 1
        )[0]
        char = core_text.split("def unicode_identifier_char_width(", 1)[1].split(
            "def starts_unicode_identifier(", 1
        )[0]
    except IndexError as error:
        raise SystemExit("lexer Unicode identifier entry points changed") from error
    if start.count(".is_unicode_letter_codepoint()") != 2:
        raise SystemExit("three- and four-byte identifier-start paths must use the generated letter predicate")
    if char.count(".is_unicode_letter_codepoint()") != 2 or char.count(".is_unicode_digit_codepoint()") != 2:
        raise SystemExit("three- and four-byte identifier-continuation paths must use generated letter/digit predicates")


def write_proofs(table: dict) -> None:
    BOUNDS.write_text(render_bounds(table))
    POSITIVE.write_text(render_model(table))
    NEGATIVE.write_text(render_negative(table))
    WITNESSES.write_text(render_witnesses(table))


def run_proof(path: Path) -> tuple[int, dict]:
    process = subprocess.run([str(BIN), "--json", str(path)], capture_output=True,
                             text=True, timeout=180)
    try:
        report = json.loads(process.stdout)
    except json.JSONDecodeError as error:
        raise SystemExit(f"proof assistant did not return JSON for {path.name}: {process.stderr}") from error
    if report["summary"]["semantic_errors"] != 0:
        raise SystemExit(f"semantic error in {path.name}: {report.get('semantic_diagnostics')}")
    if report["trust"]["trusted_assumptions"]:
        raise SystemExit(f"trusted assumptions present in {path.name}")
    if report["replay"]["gaps"] != 0:
        raise SystemExit(f"certificate replay gap in {path.name}: {report['replay']}")
    if not (report["replay"]["certificates"] == report["replay"]["replayed"] == report["summary"]["proven"]):
        raise SystemExit(f"certificate replay count mismatch in {path.name}")
    return process.returncode, report


def proof_function_blocks(path: Path) -> list[tuple[str, str]]:
    blocks = []
    current_name = None
    current_lines = []

    def finish() -> None:
        nonlocal current_name, current_lines
        if current_name is not None:
            blocks.append((current_name, "\n".join(current_lines).rstrip() + "\n"))
            current_name = None
            current_lines = []

    for line in path.read_text().splitlines():
        if line.startswith("def "):
            finish()
            current_name = line.split("(", 1)[0][4:]
            current_lines = [line]
        elif current_name is not None:
            if not line:
                finish()
            elif line.startswith("    "):
                current_lines.append(line)
            else:
                raise SystemExit(f"unsupported top-level proof syntax in {path.name}: {line}")
    finish()
    if len({name for name, _ in blocks}) != len(blocks):
        raise SystemExit(f"duplicate proof function in {path.name}")
    return blocks


def run_isolated_proof(path: Path, functions: list[tuple[str, str]], workdir: Path,
                       *, expect_false: bool = False) -> int:
    if not functions:
        raise SystemExit(f"no proof functions found in {path.name}")
    verified_count = 0
    for name, body in functions:
        isolated = workdir / f"{name}.elisa"
        isolated.write_text(body)
        code, report = run_proof(isolated)
        if report["summary"]["declarations"] != 1:
            raise SystemExit(f"isolated proof {name} does not contain exactly one declaration")
        if expect_false:
            findings = report["findings"]
            if (code != 1 or report["status"] != "failed" or
                    [finding.get("name") for finding in findings] != [name] or
                    any(finding.get("kind") != "ensure-unproven" for finding in findings)):
                raise SystemExit(f"false Unicode claim {name} was not rejected precisely")
            if report["summary"]["unproven"] != 1:
                raise SystemExit(f"false Unicode claim {name} introduced unrelated proof failures")
            observed_warnings = Counter(
                (item.get("kind_code"), item.get("severity"), item.get("message"))
                for item in report["semantic_diagnostics"]
            )
            if observed_warnings != FALSE_CLAIM_WARNING_FINGERPRINTS.get(name, Counter()):
                raise SystemExit(f"false Unicode claim {name} warning fingerprint changed")
        else:
            if code != 0 or report["status"] != "proved" or report["verification_state"] != "proved":
                raise SystemExit(f"Unicode proof {name} did not prove: {report['findings']}")
            observed_warnings = Counter(
                (item.get("kind_code"), item.get("severity"), item.get("message"))
                for item in report["semantic_diagnostics"]
            )
            if report["findings"] or observed_warnings:
                raise SystemExit(f"Unicode proof {name} has findings or unexpected semantic diagnostics")
            verified = {row["name"] for row in report["declaration_details"] if row.get("verified")}
            if verified != {name} or report["summary"]["proven"] != report["summary"]["obligations"]:
                raise SystemExit(f"Unicode proof {name} has unproven obligations")
            verified_count += report["summary"]["proven"]

        # Resource accounting is per proof invocation. Replay every declaration in
        # isolation so one generated table cannot consume another theorem's budget.
        repeated_code, repeated = run_proof(isolated)
        if (repeated_code, repeated) != (code, report):
            raise SystemExit(f"isolated Unicode proof report changed for {name}")
    return verified_count


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-proofs", action="store_true",
                        help="regenerate the deterministic proof projections from production source")
    args = parser.parse_args()
    if not __debug__:
        raise SystemExit("run without Python -O")

    table = parse_table()
    if args.write_proofs:
        write_proofs(table)
        check_source_binding(table)
        print(f"wrote {BOUNDS.name}, {POSITIVE.name}, {WITNESSES.name}, and {NEGATIVE.name}")
        return 0

    check_source_binding(table)
    try:
        product = require_current_product(BIN, PROVER)
    except (OSError, ValueError, json.JSONDecodeError, subprocess.CalledProcessError) as error:
        raise SystemExit(f"proof product provenance check failed: {error}") from error
    if product.get("compile_mode") != "strict":
        raise SystemExit("Unicode range proofs require a strict proof build")

    compiler = product["compiler"]
    compiler_head = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], check=True,
                                   capture_output=True, text=True).stdout.strip()
    if compiler_head != compiler["source_revision"]:
        raise SystemExit("proof product compiler revision does not match the checked-out compiler HEAD")

    stage1_product = Path(compiler["product"]["path"]).resolve(strict=True)
    stage1_provenance = Path(str(stage1_product) + ".provenance.json").resolve(strict=True)
    roots = [BOUNDS, POSITIVE, NEGATIVE, WITNESSES, FACADE]
    inputs = list(dict.fromkeys([
        BIN, BIN.with_name(BIN.name + ".manifest.json"),
        BIN.with_name(BIN.name + ".manifest.json.sha256"),
        PROVER / "ELISA_COMPILER_REV", stage1_product, stage1_provenance,
        Path(__file__), HERE / "proof_product_gate.py", SOURCE, FACADE, CORE, GENERATOR,
        BOUNDS, POSITIVE, NEGATIVE, WITNESSES, *source_include_closure(roots),
    ]))
    hashes_before = {str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in inputs}

    expected_positive = {
        f"{name}_{'intervals_are_valid_and_ordered' if item['kind'] == 'leaf' else 'page_intervals_are_valid_and_ordered'}"
        for name, item in table.items() if item["kind"] in ("leaf", "dispatch")
    }
    expected_positive.update(
        f"proof_{name}_accumulates_source_intervals" if item["kind"] == "leaf" else
        f"proof_{name}_accumulates_source_parts" if item["kind"] == "aggregate" else
        f"proof_{name}_routes_inside_page_intervals" if item["kind"] == "dispatch" else
        f"proof_{name}_preserves_dispatch_result"
        for name, item in table.items()
    )
    expected_positive.update({
        "unicode_letter_cjk_extension_a_lower_boundary_is_in_table",
        "unicode_letter_cjk_extension_a_upper_boundary_is_in_table",
        "unicode_digit_mathematical_digit_lower_boundary_is_in_table",
        "unicode_digit_mathematical_digit_upper_boundary_is_in_table",
        "unicode_digit_scalar_before_mathematical_digits_is_outside_table",
        "unicode_digit_scalar_after_mathematical_digits_is_outside_table",
        "unicode_letter_first_generated_lower_boundary_is_in_table",
        "unicode_letter_final_generated_upper_boundary_is_in_table",
        "unicode_letter_scalar_after_final_generated_range_is_outside_table",
        "unicode_letter_supplementary_boundary_routes_to_page_one",
        "unicode_letter_scalar_after_last_dispatch_page_is_unrouted",
        "unicode_surrogate_interval_is_not_a_scalar_interval",
    })
    bound_blocks = proof_function_blocks(BOUNDS)
    model_blocks = proof_function_blocks(POSITIVE)
    witness_blocks = proof_function_blocks(WITNESSES)
    observed_positive = {name for name, _ in bound_blocks + model_blocks + witness_blocks}
    if observed_positive != expected_positive:
        raise SystemExit("Unicode classifier positive proof declarations do not match the rendered source")
    with tempfile.TemporaryDirectory(prefix="elisa-unicode-proof-") as temporary:
        workdir = Path(temporary)
        positive_obligations = (
            run_isolated_proof(BOUNDS, bound_blocks, workdir) +
            run_isolated_proof(POSITIVE, model_blocks, workdir)
        )

    expected_false_claims = {
        "false_cjk_extension_a_start_is_not_a_letter",
        "false_mathematical_decimal_digit_start_is_not_a_digit",
        "false_supplementary_letter_uses_the_bmp_page",
        "false_codepoint_above_generated_pages_is_reported",
        "false_surrogate_span_is_a_scalar_interval",
        "false_generated_intervals_are_not_strictly_ordered",
    }
    negative_blocks = proof_function_blocks(NEGATIVE)
    if {name for name, _ in negative_blocks} != expected_false_claims:
        raise SystemExit("Unicode false-control declarations changed")
    with tempfile.TemporaryDirectory(prefix="elisa-unicode-false-claims-") as temporary:
        run_isolated_proof(NEGATIVE, negative_blocks, Path(temporary), expect_false=True)

    witness_warning_counts = {
        "unicode_letter_cjk_extension_a_lower_boundary_is_in_table": 24,
        "unicode_letter_cjk_extension_a_upper_boundary_is_in_table": 24,
        "unicode_digit_mathematical_digit_lower_boundary_is_in_table": 22,
        "unicode_digit_mathematical_digit_upper_boundary_is_in_table": 22,
        "unicode_digit_scalar_before_mathematical_digits_is_outside_table": 22,
        "unicode_digit_scalar_after_mathematical_digits_is_outside_table": 22,
        "unicode_letter_first_generated_lower_boundary_is_in_table": 19,
        "unicode_letter_final_generated_upper_boundary_is_in_table": 4,
        "unicode_letter_scalar_after_final_generated_range_is_outside_table": 4,
        "unicode_letter_supplementary_boundary_routes_to_page_one": 12,
        "unicode_letter_scalar_after_last_dispatch_page_is_unrouted": 12,
        "unicode_surrogate_interval_is_not_a_scalar_interval": 5,
    }
    # Literal boundary witnesses intentionally make their arithmetic concrete;
    # pin the constant-folding diagnostics so unrelated warnings remain rejected.
    warning_fingerprint = Counter({
        (82, 2, "constant comparison is always true"): 97,
        (82, 2, "constant comparison is always false"): 87,
        (102, 2, "logical operator with constant boolean operand"): 8,
    })
    for name in witness_warning_counts:
        witness = [(candidate, body) for candidate, body in witness_blocks if candidate == name]
        if len(witness) != 1:
            raise SystemExit(f"missing concrete Unicode witness {name}")
    # Each theorem is replayed alone; this aggregate fingerprint also catches
    # source-boundary edits that change the expected constant warning profile.
    observed_witness_warnings = Counter()
    with tempfile.TemporaryDirectory(prefix="elisa-unicode-witnesses-") as temporary:
        for name, body in witness_blocks:
            isolated = Path(temporary) / f"{name}.elisa"
            isolated.write_text(body)
            code, report = run_proof(isolated)
            verified = {row["name"] for row in report["declaration_details"] if row.get("verified")}
            if (code != 0 or report["status"] != "proved" or report["verification_state"] != "proved" or
                    report["summary"]["declarations"] != 1 or report["summary"]["unproven"] or
                    report["summary"]["proven"] != report["summary"]["obligations"] or verified != {name}):
                raise SystemExit(f"Unicode witness {name} did not prove")
            observed = Counter(
                (item.get("kind_code"), item.get("severity"), item.get("message"))
                for item in report["semantic_diagnostics"]
            )
            if sum(observed.values()) != witness_warning_counts[name]:
                raise SystemExit(f"Unicode witness {name} warning fingerprint changed")
            observed_witness_warnings.update(observed)
            positive_obligations += report["summary"]["proven"]
            repeated_code, repeated = run_proof(isolated)
            if (repeated_code, repeated) != (code, report):
                raise SystemExit(f"Unicode witness report changed for {name}")
    if observed_witness_warnings != warning_fingerprint:
        raise SystemExit("Unicode witness warning profile differs from the expected constant folds")

    if product != require_current_product(BIN, PROVER):
        raise SystemExit("proof product changed during Unicode proof replay")
    hashes_after = {str(path): hashlib.sha256(path.read_bytes()).hexdigest() for path in inputs}
    if hashes_before != hashes_after:
        raise SystemExit("a source, proof, or executable changed during Unicode proof replay")

    print(json.dumps({
        "admitted": True,
        "scope": "all generated Unicode letter/digit intervals, OR reductions, and page routing",
        "unicode_version": SOURCE.read_text().splitlines()[0],
        "interval_atoms": sum(len(item["atoms"]) for item in table.values() if item["kind"] == "leaf"),
        "positive_obligations": positive_obligations,
        "false_claims_refused": sorted(expected_false_claims),
        "proof_revision": product["proof"].get("head"),
        "compiler_revision": compiler.get("source_revision"),
        "source_sha256": hashes_before,
    }, sort_keys=True))
    return 0


